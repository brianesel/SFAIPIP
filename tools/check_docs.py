#!/usr/bin/env python3
"""Check that every workflow step checks guardrails, and that every guardrail is used where it applies.

usage: check_docs.py [--write-index]
  - every row of a "Steps" table (column 'Guardrails') in workflow/phases/*.md cites ≥1 guardrail ID
  - every cited ID exists in guardrails/registry.yaml
  - every guardrail listed for a phase is cited in that phase's workflow
  --write-index regenerates guardrails/README.md from the registry
Exit 1 on any problem.
"""
import re
import sys
from pathlib import Path

import yaml

PKG = Path(__file__).resolve().parents[1]
REG = yaml.safe_load((PKG / "guardrails/registry.yaml").read_text())["guardrails"]
ID_RE = re.compile(r"\b(HG-\d{2}|PR-\d{2}|AI-\d{2}|G[0-5])\b")
PHASE_FILES = {"intake": "00-intake", "eval": "01-eval", "discovery": "02-discovery", "alignment": "03-alignment",
               "requirements": "04-requirements", "refinement": "05-refinement", "dev": "06-dev", "delivery": "07-delivery"}


def step_rows(text):
    """Yield (step label, guardrail cell) for tables whose header has a 'Guardrails' column."""
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        if lines[i].startswith("|") and "Guardrails" in lines[i]:
            head = [c.strip() for c in lines[i].strip("|").split("|")]
            gi = head.index("Guardrails")
            i += 2  # skip separator
            while i < len(lines) and lines[i].startswith("|"):
                cells = [c.strip() for c in lines[i].strip("|").split("|")]
                yield cells[0] + " " + (cells[1] if len(cells) > 1 else ""), cells[gi] if gi < len(cells) else ""
                i += 1
        i += 1


def main():
    errs = []
    cited_by_phase = {}
    for phase, stem in PHASE_FILES.items():
        f = PKG / "workflow/phases" / f"{stem}.md"
        if not f.exists():
            errs.append(f"missing workflow file {f.relative_to(PKG)}")
            continue
        text = f.read_text()
        rows = list(step_rows(text))
        if not rows:
            errs.append(f"{f.name}: no Steps table with a 'Guardrails' column")
        for label, cell in rows:
            ids = ID_RE.findall(cell)
            if not ids:
                errs.append(f"{f.name}: step '{label[:50]}' cites no guardrail")
        cited = set(ID_RE.findall(text))
        cited_by_phase[phase] = cited
        for i in cited - set(REG):
            errs.append(f"{f.name}: unknown guardrail {i}")
    for gid, g in REG.items():
        for ph in g["phases"]:
            if ph in cited_by_phase and gid not in cited_by_phase[ph]:
                errs.append(f"{gid} applies to '{ph}' but {PHASE_FILES[ph]}.md never cites it")
    for f in (PKG / "workflow").rglob("*.md"):
        for i in set(ID_RE.findall(f.read_text())) - set(REG):
            errs.append(f"{f.relative_to(PKG)}: unknown guardrail {i}")

    for f in sorted((PKG / "guardrails/rubric").glob("*.yaml")):
        if f.name == "pillars.yaml":
            continue
        for c in yaml.safe_load(f.read_text())["checks"]:
            if c.get("guardrail") and c["guardrail"] not in REG:
                errs.append(f"rubric {c['id']}: unknown guardrail {c['guardrail']}")
            if c["type"] == "gate" and not c.get("guardrail"):
                errs.append(f"rubric {c['id']}: gate check must map to a guardrail ID")

    if "--write-index" in sys.argv:
        write_index()
    if errs:
        print("❌ workflow ↔ guardrails check failed")
        print("\n".join(f"- {e}" for e in errs))
        sys.exit(1)
    print(f"✅ {len(PHASE_FILES)} phase workflows; every step cites guardrails; {len(REG)} guardrails all covered where they apply")


def write_index():
    L = ["# Guardrails", "",
         "What must always hold. Source of truth: `registry.yaml`. Generated by `tools/check_docs.py --write-index` — do not edit by hand.", "",
         "Types: **hard** never overridden (waiver for existing code only) · **gate** phase exit · **process** · **ai** AI behaviour.", "",
         "Also here: `rubric/` (how guardrails are measured and scored) · `schemas/` (required ticket and test-case fields).", ""]
    for t, title in (("hard", "Hard rules"), ("gate", "Gates"), ("process", "Process rules"), ("ai", "AI rules")):
        L += [f"## {title}", "", "| ID | Rule | Override | Enforced by | Phases |", "|---|---|---|---|---|"]
        for gid, g in REG.items():
            if g["type"] == t:
                L.append(f"| {gid} | {g['rule']} | {g['override']} | {', '.join(g['enforced_by'])} | {', '.join(g['phases'])} |")
        L.append("")
    (PKG / "guardrails/README.md").write_text("\n".join(L))


if __name__ == "__main__":
    main()
