#!/usr/bin/env python3
"""Analyzer rules for guardrails: find existing rules, generate missing ones, prove they work.

usage: rule_map.py <command> [--project DIR]
  inventory [--from rules.json]   list installed Code Analyzer rules → .sfg/rules-inventory.json
  generate                        rules/custom-rules.yaml + guardrails/analyzer-map.yaml →
                                  rules/generated/pmd-custom.xml + code-analyzer.yml (tags 'Project', severities)
  test [--rule ID]                run each custom rule on its bad/good fixtures (needs sf + code-analyzer)
  coverage                        report per guardrail and project rule → docs/wiki/_data/analyzer-coverage.md
Exit 1 from `test`/`coverage` when something fails or is uncovered.
CI selector after generate:  sf code-analyzer run --rule-selector Recommended --rule-selector Project
"""
import datetime as dt
import hashlib
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from xml.sax.saxutils import escape

import yaml

PKG = Path(__file__).resolve().parents[1]
AMAP = yaml.safe_load((PKG / "guardrails/analyzer-map.yaml").read_text())
REG = yaml.safe_load((PKG / "guardrails/registry.yaml").read_text())["guardrails"]
GEN_DIR = Path("rules/generated")
PMD_XML = GEN_DIR / "pmd-custom.xml"
RESULTS = GEN_DIR / "test-results.json"
INVENTORY = Path(".sfg/rules-inventory.json")
HEADER = ("# Generated by tools/rule_map.py generate — edit rules/custom-rules.yaml or guardrails/analyzer-map.yaml instead.\n"
          "# CI: sf code-analyzer run --rule-selector Recommended --rule-selector Project --severity-threshold 2\n")
DEFAULT_EXT = {"pmd": ".cls", "regex": ".cls"}


def sf_bin():
    return shutil.which("sf") or sys.exit("sf CLI not found (needed for inventory/test)")


def load_specs(root):
    f = root / "rules/custom-rules.yaml"
    return (yaml.safe_load(f.read_text()) or {}).get("rules") or [] if f.exists() else []


def spec_hash(s):
    keep = {k: v for k, v in s.items() if k not in ("approved_by",)}
    return hashlib.sha256(json.dumps(keep, sort_keys=True).encode()).hexdigest()[:12]


def load_inventory(root):
    f = root / INVENTORY
    if not f.exists():
        return None
    return {(r["engine"], r["name"]): r for r in json.loads(f.read_text())["rules"]}


# ---------- inventory ----------
def cmd_inventory(root, src):
    out = root / INVENTORY
    out.parent.mkdir(exist_ok=True)
    if src:
        shutil.copy(src, out)
    else:
        r = subprocess.run([sf_bin(), "code-analyzer", "rules", "--rule-selector", "all", "--output-file", str(out)],
                           capture_output=True, text=True, timeout=600)
        if r.returncode != 0 or not out.exists():
            sys.exit("inventory failed:\n" + r.stderr[-800:])
    inv = load_inventory(root)
    by = {}
    for e, _ in inv:
        by[e] = by.get(e, 0) + 1
    print(f"{len(inv)} rules installed: " + ", ".join(f"{e} {n}" for e, n in sorted(by.items())) + f" → {INVENTORY}")


# ---------- generate ----------
def pmd_xml(specs):
    rules = []
    for s in specs:
        rules.append(f'''  <rule name="{s['id']}" language="apex" message="{escape(s['message'])}"
        class="net.sourceforge.pmd.lang.rule.xpath.XPathRule">
    <description>{escape(s.get('intent', ''))} [{s.get('guardrail', '')}]</description>
    <priority>1</priority>
    <properties><property name="xpath"><value><![CDATA[{s['xpath']}]]></value></property></properties>
  </rule>''')
    return ('<?xml version="1.0"?>\n<ruleset name="Project custom rules" xmlns="http://pmd.sourceforge.net/ruleset/2.0.0"\n'
            '  xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"\n'
            '  xsi:schemaLocation="http://pmd.sourceforge.net/ruleset/2.0.0 https://pmd.sourceforge.io/ruleset_2_0_0.xsd">\n'
            '  <description>Generated from rules/custom-rules.yaml</description>\n' + "\n".join(rules) + "\n</ruleset>\n")


def regex_rule(s):
    exts = s.get("file_extensions") or [".cls", ".trigger"]
    r = {"regex": s["regex"], "file_extensions": exts, "description": s.get("intent", s["id"]),
         "violation_message": s["message"], "severity": int(s.get("severity", 2)), "tags": ["Project", "Custom"]}
    if s.get("regex_ignore"):
        r["regex_ignore"] = s["regex_ignore"]
    if any(e.endswith("-meta.xml") for e in exts) or s.get("include_metadata"):
        r["include_metadata"] = True
    return r


def build_config(root, specs, inv, cfg=None):
    cfg = cfg or {}
    eng = cfg.setdefault("engines", {})
    pmd_specs = [s for s in specs if s["engine"] == "pmd"]
    if pmd_specs:
        rs = eng.setdefault("pmd", {}).setdefault("custom_rulesets", [])
        if str(PMD_XML) not in rs:
            rs.append(str(PMD_XML))
    rx = {s["id"]: regex_rule(s) for s in specs if s["engine"] == "regex"}
    if rx:
        eng.setdefault("regex", {})["custom_rules"] = rx
    rules = cfg.setdefault("rules", {})
    warnings = []

    def tag(engine, name, severity=None):
        base = list(inv[(engine, name)]["tags"]) if inv and (engine, name) in inv else ["Recommended"]
        if inv and (engine, name) not in inv:
            warnings.append(f"{engine}:{name} not installed — check the name or analyzer version")
        ent = rules.setdefault(engine, {}).setdefault(name, {})
        ent["tags"] = sorted(set(base) | {"Project"}, key=lambda t: (t != "Recommended", t))
        if severity:
            ent["severity"] = int(severity)

    for gid, lst in AMAP["guardrails"].items():
        for m in lst:
            e, n = m["rule"].split(":", 1)
            tag(e, n, m.get("severity"))
    for lst in AMAP["rubric"].values():
        for r in lst:
            e, n = r.split(":", 1)
            tag(e, n)
    for s in pmd_specs:
        rules.setdefault("pmd", {})[s["id"]] = {"severity": int(s.get("severity", 2)), "tags": ["Project", "Custom"]}
    return cfg, warnings


def validate_specs(specs):
    errs, seen = [], set()
    for s in specs:
        sid = s.get("id", "?")
        if sid in seen:
            errs.append(f"{sid}: duplicate id")
        seen.add(sid)
        if s.get("engine") not in ("pmd", "regex"):
            errs.append(f"{sid}: engine must be pmd or regex (flow engine has no custom rules — use regex on .flow-meta.xml)")
        if s.get("engine") == "pmd" and not s.get("xpath"):
            errs.append(f"{sid}: pmd rule needs xpath")
        if s.get("engine") == "regex" and not str(s.get("regex", "")).startswith("/"):
            errs.append(f"{sid}: regex must look like /pattern/flags")
        for k in ("message", "guardrail", "intent"):
            if not s.get(k):
                errs.append(f"{sid}: {k} missing")
        t = s.get("tests") or {}
        if not t.get("bad") or not t.get("good"):
            errs.append(f"{sid}: tests.bad and tests.good fixtures required")
    return errs


def cmd_generate(root):
    specs = load_specs(root)
    errs = validate_specs(specs)
    if errs:
        sys.exit("custom-rules.yaml invalid:\n- " + "\n- ".join(errs))
    inv = load_inventory(root)
    (root / GEN_DIR).mkdir(parents=True, exist_ok=True)
    pmd_specs = [s for s in specs if s["engine"] == "pmd"]
    if pmd_specs:
        (root / PMD_XML).write_text(pmd_xml(pmd_specs))
    cfgf = root / "code-analyzer.yml"
    cfg = yaml.safe_load(cfgf.read_text()) if cfgf.exists() else {}
    cfg, warnings = build_config(root, specs, inv, cfg or {})
    cfgf.write_text(HEADER + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True))
    print(f"✅ generated: {len(pmd_specs)} PMD + {len(specs) - len(pmd_specs)} regex custom rules; "
          f"{sum(len(v) for v in cfg['rules'].values())} rule overrides in code-analyzer.yml")
    if not inv:
        print("! no inventory: tags not merged with built-in tags — run `inventory` first, then `generate` again")
    for w in warnings:
        print(f"! {w}")


# ---------- test ----------
def run_fixture(root, s, inv):
    ext = (s.get("file_extensions") or [DEFAULT_EXT[s["engine"]]])[0]
    with tempfile.TemporaryDirectory() as td:
        td = Path(td)
        d = td / "force-app/main/default/src"
        d.mkdir(parents=True)
        (d / f"Bad{ext}").write_text(s["tests"]["bad"])
        (d / f"Good{ext}").write_text(s["tests"]["good"])
        cfg = {"engines": {}}
        if s["engine"] == "pmd":
            (td / "r.xml").write_text(pmd_xml([s]))
            cfg["engines"]["pmd"] = {"custom_rulesets": [str(td / "r.xml")]}
        else:
            cfg["engines"]["regex"] = {"custom_rules": {s["id"]: regex_rule(s)}}
        (td / "code-analyzer.yml").write_text(yaml.safe_dump(cfg))
        out = td / "out.json"
        r = subprocess.run([sf_bin(), "code-analyzer", "run", "--workspace", str(td), "--rule-selector",
                            f"{s['engine']}:{s['id']}", "--config-file", str(td / "code-analyzer.yml"),
                            "--output-file", str(out)], capture_output=True, text=True, timeout=600, cwd=td)
        if not out.exists():
            return False, f"analyzer error: {r.stderr[-300:] or r.stdout[-300:]}"
        v = [x for x in json.loads(out.read_text())["violations"] if x["rule"] == s["id"]]
        files = [x["locations"][x.get("primaryLocationIndex", 0)]["file"] for x in v]
        bad = sum("Bad" in Path(f).name for f in files)
        good = sum("Good" in Path(f).name for f in files)
        ok = bad >= 1 and good == 0
        return ok, f"bad fixture: {bad} hit(s) · good fixture: {good} hit(s)"


def cmd_test(root, only):
    specs = [s for s in load_specs(root) if not only or s["id"] == only]
    errs = validate_specs(specs)
    if errs:
        sys.exit("custom-rules.yaml invalid:\n- " + "\n- ".join(errs))
    resf = root / RESULTS
    resf.parent.mkdir(parents=True, exist_ok=True)
    res = json.loads(resf.read_text()) if resf.exists() else {}
    fail = False
    for s in specs:
        ok, detail = run_fixture(root, s, None)
        res[s["id"]] = {"passed": ok, "hash": spec_hash(s), "date": dt.date.today().isoformat(), "detail": detail}
        print(f"{'✅' if ok else '❌'} {s['id']} ({s['engine']}): {detail}")
        fail |= not ok
    resf.write_text(json.dumps(res, indent=2))
    sys.exit(1 if fail else 0)


# ---------- coverage ----------
def cmd_coverage(root):
    inv = load_inventory(root)
    if not inv:
        sys.exit("No inventory. Run: rule_map.py inventory")
    specs = load_specs(root)
    res = json.loads((root / RESULTS).read_text()) if (root / RESULTS).exists() else {}
    cfgf = root / "code-analyzer.yml"
    cfg = yaml.safe_load(cfgf.read_text()) if cfgf.exists() else {}
    proj = yaml.safe_load((root / "guardrails.project.yaml").read_text()) if (root / "guardrails.project.yaml").exists() else {}
    rows, problems = [], []

    def spec_status(gid):
        out = []
        for s in [x for x in specs if x.get("guardrail") == gid]:
            r = res.get(s["id"])
            if not r or r["hash"] != spec_hash(s):
                st = "untested"
            elif not r["passed"]:
                st = "failing"
            elif not s.get("approved_by"):
                st = "unapproved"
            else:
                st = "ok"
            out.append((s["id"], st))
        return out

    for gid, g in REG.items():
        mapped = AMAP["guardrails"].get(gid, [])
        alt = AMAP["not_analyzer"].get(gid)
        customs = spec_status(gid)
        if not mapped and not customs and not alt:
            if "code-analyzer" in g["enforced_by"]:
                rows.append((gid, "❌ missing", "registry says code-analyzer, no rule mapped"))
                problems.append(gid)
            continue
        present = [m["rule"] for m in mapped if tuple(m["rule"].split(":", 1)) in inv]
        absent = [m["rule"] for m in mapped if tuple(m["rule"].split(":", 1)) not in inv]
        stale = [m["rule"] for m in mapped
                 if m.get("severity") and (cfg.get("rules", {}).get(m["rule"].split(":")[0], {})
                                           .get(m["rule"].split(":", 1)[1], {}).get("severity") != m["severity"])]
        parts = []
        if present:
            parts.append("built-in: " + ", ".join(present))
        if customs:
            parts.append("custom: " + ", ".join(f"{i} ({st})" for i, st in customs))
        if alt:
            parts.append("other: " + alt)
        status = "✅ covered"
        if absent:
            status = "⚠ partial"
            parts.append("not installed: " + ", ".join(absent))
        if stale:
            status = "⚠ config stale"
            parts.append("severity override missing (run generate): " + ", ".join(stale))
        if any(st != "ok" for _, st in customs):
            status = "⚠ custom rule not ready"
            problems.append(gid)
        if not present and not alt and not any(st == "ok" for _, st in customs):
            status = "❌ missing"
            problems.append(gid)
        rows.append((gid, status, " · ".join(parts)))

    prj_rows = []
    for pr in proj.get("project_rules") or []:
        pid = pr.get("id")
        enforce = pr.get("enforce", "analyzer")
        customs = spec_status(pid)
        if enforce != "analyzer":
            prj_rows.append((pid, f"➖ {enforce}", pr.get("rule", "")))
            continue
        if not customs:
            prj_rows.append((pid, "❌ no rule — draft one in rules/custom-rules.yaml", pr.get("rule", "")))
            problems.append(pid)
        elif all(st == "ok" for _, st in customs):
            prj_rows.append((pid, "✅ " + ", ".join(i for i, _ in customs), pr.get("rule", "")))
        else:
            prj_rows.append((pid, "⚠ " + ", ".join(f"{i} ({st})" for i, st in customs), pr.get("rule", "")))
            problems.append(pid)

    L = [f"# Analyzer coverage — {dt.date.today()}", "",
         f"**Verdict: {'✅ every analyzer-enforced guardrail has a working rule' if not problems else '❌ gaps: ' + ', '.join(sorted(set(problems)))}**", "",
         f"Installed rules: {len(inv)}. CI selector: `--rule-selector Recommended --rule-selector Project --severity-threshold 2`.", "",
         "## Baseline guardrails", "", "| Guardrail | Status | Enforced by |", "|---|---|---|"]
    L += [f"| {g} | {s} | {d} |" for g, s, d in rows]
    L += ["", "## Project rules (guardrails.project.yaml → project_rules)", "", "| Rule | Status | Intent |", "|---|---|---|"]
    L += [f"| {g} | {s} | {d} |" for g, s, d in prj_rows] or ["| – | none defined | |"]
    text = "\n".join(L) + "\n"
    outf = root / "docs/wiki/_data/analyzer-coverage.md"
    outf.parent.mkdir(parents=True, exist_ok=True)
    outf.write_text(text)
    print(text)
    sys.exit(1 if problems else 0)


def main():
    a = sys.argv[1:]
    if not a:
        sys.exit(__doc__)
    root = Path(a[a.index("--project") + 1] if "--project" in a else ".").resolve()
    cmd = a[0]
    if cmd == "inventory":
        cmd_inventory(root, a[a.index("--from") + 1] if "--from" in a else None)
    elif cmd == "generate":
        cmd_generate(root)
    elif cmd == "test":
        cmd_test(root, a[a.index("--rule") + 1] if "--rule" in a else None)
    elif cmd == "coverage":
        cmd_coverage(root)
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
